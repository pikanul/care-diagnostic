function setupMenu() {
  const toggle = document.querySelector("[data-menu-toggle]");
  const nav = document.querySelector("[data-site-nav]");
  if (!toggle || !nav) return;
  toggle.addEventListener("click", () => {
    const open = nav.classList.toggle("is-open");
    toggle.setAttribute("aria-expanded", String(open));
  });
}

function setupCarousel() {
  const prev = document.querySelector("[data-carousel-prev]");
  const next = document.querySelector("[data-carousel-next]");
  const track = document.querySelector("[data-doctors]");
  if (!prev || !next || !track) return;
  const scrollByAmount = () => Math.max(280, track.clientWidth * 0.75);
  prev.addEventListener("click", () => track.scrollBy({ left: -scrollByAmount(), behavior: "smooth" }));
  next.addEventListener("click", () => track.scrollBy({ left: scrollByAmount(), behavior: "smooth" }));
}

function setupNavActive() {
  const navLinks = [...document.querySelectorAll(".nav__link")];
  if (!navLinks.length) return;
  const observer = new IntersectionObserver(
    (entries) => {
      const visible = entries.filter((entry) => entry.isIntersecting).sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];
      if (!visible) return;
      navLinks.forEach((link) => link.classList.toggle("is-active", link.getAttribute("href") === `#${visible.target.id}`));
    },
    { threshold: 0.35 }
  );

  document.querySelectorAll("main section[id]").forEach((section) => observer.observe(section));
}

